"""
MARKET EDGE AI V5
NFL AUTOMATED PREDICTION PIPELINE

Purpose:
Run the existing NFL live-prediction workflow from one function
instead of requiring the user to manually execute each stage.
"""

from dual_agent.nfl_odds import (
    get_live_nfl_moneylines,
    get_best_nfl_moneylines,
)

from dual_agent.nfl_live_engine import (
    build_live_nfl_opportunities,
)

import pandas as pd

from dual_agent.nfl_research import (
    build_nfl_future_matchup_features,
    predict_nfl_matchup,
)


def run_nfl_prediction_pipeline(
    feature_games,
    historical_accuracy=None,
    historical_sample=None,
):
    """
    Run the NFL live market workflow.

    Parameters
    ----------
    predictions:
        Existing NFL model predictions generated by the
        Market Edge AI NFL prediction engine.

    Returns
    -------
    dict
        Raw sportsbook odds, best available lines,
        model predictions, and final market opportunities.
    """

    if predictions is None:
        raise ValueError(
            "NFL model predictions were not supplied."
        )

    if hasattr(predictions, "empty"):
        if predictions.empty:
            raise ValueError(
                "NFL model predictions are empty."
            )

    elif not predictions:
        raise ValueError(
            "NFL model predictions are empty."
        )

    # ==========================================
    # 1. LOAD LIVE NFL MONEYLINES
    # ==========================================

    live_odds = get_live_nfl_moneylines()

    if live_odds is None:
        raise ValueError(
            "NFL live odds retrieval returned no data."
        )

        # ==========================================
    # 3. GENERATE UPCOMING NFL PREDICTIONS
    # ==========================================

    if feature_games is None:
        raise ValueError(
            "NFL historical feature data was not supplied."
        )

    if hasattr(feature_games, "empty") and feature_games.empty:
        raise ValueError(
            "NFL historical feature data is empty."
        )

    prediction_rows = []
    prediction_errors = []

    current_time = pd.Timestamp.now(tz="UTC")

    # Normalize best lines to a DataFrame for prediction loop.
    if isinstance(best_lines, pd.DataFrame):
        best_lines_df = best_lines.copy()
    else:
        best_lines_df = pd.DataFrame(best_lines)

    for _, game in best_lines_df.iterrows():

        home_team = game["home_team"]
        away_team = game["away_team"]

        game_time = pd.to_datetime(
            game["commence_time"],
            utc=True,
            errors="coerce",
        )

        if pd.isna(game_time):
            continue

        # Never generate a prediction after kickoff.
        if game_time <= current_time:
            continue

        try:
            future_features = (
                build_nfl_future_matchup_features(
                    feature_games,
                    home_team,
                    away_team,
                    game_time,
                )
            )

            prediction = predict_nfl_matchup(
                feature_games,
                future_features,
            )

            home_probability = prediction[
                "home_win_probability"
            ]

            away_probability = (
                prediction.get(
                    "away_win_probability",
                    1.0 - home_probability,
                )
            )

            if home_probability >= away_probability:
                predicted_team = home_team
                confidence = home_probability
            else:
                predicted_team = away_team
                confidence = away_probability

            prediction_rows.append(
                {
                    "game_id": game.get("game_id"),
                    "commence_time": game_time,
                    "home_team": home_team,
                    "away_team": away_team,
                    "predicted_team": predicted_team,
                    "confidence": confidence,
                    "home_win_probability": home_probability,
                    "away_win_probability": away_probability,
                    "training_games": prediction.get(
                        "training_games"
                    ),
                }
            )

        except Exception as error:
            prediction_errors.append(
                f"{away_team} at {home_team}: {error}"
            )

    predictions = pd.DataFrame(prediction_rows)

    if predictions.empty:
        error_preview = "; ".join(
            prediction_errors[:3]
        )

        raise ValueError(
            "No upcoming NFL predictions could be generated."
            + (
                f" Errors: {error_preview}"
                if error_preview
                else ""
            )
        )

    if hasattr(live_odds, "empty"):
        if live_odds.empty:
            raise ValueError(
                "No live NFL moneylines are available."
            )

    elif not live_odds:
        raise ValueError(
            "No live NFL moneylines are available."
        )

    # ==========================================
    # 2. FIND BEST AVAILABLE MONEYLINES
    # ==========================================

    best_lines = get_best_nfl_moneylines(
        live_odds
    )

    if best_lines is None:
        raise ValueError(
            "NFL best-line calculation returned no data."
        )

    if hasattr(best_lines, "empty"):
        if best_lines.empty:
            raise ValueError(
                "No usable NFL best lines were found."
            )

    elif not best_lines:
        raise ValueError(
            "No usable NFL best lines were found."
        )

    # 4. BUILD LIVE NFL OPPORTUNITIES

    opportunities = build_live_nfl_opportunities(
    model_predictions=predictions,
    best_lines=best_lines,
    historical_accuracy=historical_accuracy,
    historical_sample=historical_sample,
)

    if opportunities is None:
        raise ValueError(
            "NFL opportunity engine returned no results."
        )

    # ==========================================
    # 5. RETURN COMPLETE PIPELINE  
    # ==========================================

    return {
    "live_odds": live_odds,
    "best_lines": best_lines,
    "predictions": predictions,
    "opportunities": opportunities,
    "prediction_errors": prediction_errors,
}
